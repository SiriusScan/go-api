package host

import (
	"errors"
	"testing"

	"github.com/SiriusScan/go-api/sirius/scope"
	"gorm.io/gorm"
)

func TestScopedHostsDoNotCrossScopes(t *testing.T) {
	repo := portFixture(t)
	if err := repo.db.Exec(`ALTER TABLE hosts ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 10)`).Error; err != nil {
		t.Fatal(err)
	}
	alice, bob := scope.ForSubject("alice"), scope.ForSubject("bob")
	a, err := repo.UpsertHostScoped(alice, "192.0.2.1", "alice-host", "", "", "alice-hid")
	if err != nil {
		t.Fatal(err)
	}
	b, err := repo.UpsertHostScoped(bob, "192.0.2.1", "bob-host", "", "", "bob-hid")
	if err != nil {
		t.Fatal(err)
	}
	if a == b || a == 1 || b == 1 {
		t.Fatalf("non-unique host IDs: %d %d", a, b)
	}
	for _, tc := range []struct {
		scope scope.ResourceScope
		want  uint
	}{{alice, a}, {bob, b}, {scope.Global(), 1}} {
		h, err := repo.GetHostWithRelationsScoped(tc.scope, "192.0.2.1")
		if err != nil || h.Host.ID != tc.want {
			t.Fatalf("scope %+v got %+v, %v", tc.scope, h, err)
		}
		all, err := repo.GetAllHostsWithRelationsScoped(tc.scope)
		if err != nil {
			t.Fatal(err)
		}
		for _, h := range all {
			if h.Host.OwnerSubjectID != string(tc.scope.OwnerSubjectID) {
				t.Fatalf("cross-scope list: %+v", h.Host)
			}
		}
	}
	_, err = repo.GetHostWithRelationsScoped(alice, "192.0.2.2")
	if !errors.Is(err, gorm.ErrRecordNotFound) {
		t.Fatalf("expected not found, got %v", err)
	}
	if _, err := repo.UpsertHostScoped(alice, "192.0.2.1", "changed", "", "", ""); err != nil {
		t.Fatal(err)
	}
	h, err := repo.GetHostWithRelationsScoped(bob, "192.0.2.1")
	if err != nil || h.Host.Hostname != "bob-host" {
		t.Fatalf("another scope modified: %+v, %v", h, err)
	}
}
